'use server'

interface UpdatedCVData {
  originalCV: string
  missingKeywords: string[]
  recommendations: Array<{
    title: string
    description: string
    priority: 'high' | 'medium' | 'low'
  }>
  matchScore: number
  atsScore: number
  keywordMatchPercentage: number
}

/**
 * Generate an updated CV document with recommendations integrated
 * Returns plain text that can be downloaded
 */
export async function generateUpdatedCV(data: UpdatedCVData): Promise<string> {
  const {
    originalCV,
    missingKeywords,
    recommendations,
    matchScore,
    atsScore,
    keywordMatchPercentage
  } = data

  // Build the updated CV content
  let updatedContent = ''

  // Add header with analysis results
  updatedContent += '═══════════════════════════════════════════════════════════\n'
  updatedContent += 'CV OPTIMIZATION REPORT - Generated by ATS Optimizer\n'
  updatedContent += '═══════════════════════════════════════════════════════════\n\n'

  updatedContent += 'ANALYSIS SCORES:\n'
  updatedContent += `  • Overall Match Score: ${matchScore}%\n`
  updatedContent += `  • ATS Readability Score: ${atsScore}%\n`
  updatedContent += `  • Keyword Match Percentage: ${keywordMatchPercentage}%\n\n`

  // Add missing keywords section
  if (missingKeywords.length > 0) {
    updatedContent += 'IMPORTANT: MISSING KEYWORDS TO ADD:\n'
    updatedContent += 'Consider incorporating these keywords naturally in your CV:\n'
    updatedContent += missingKeywords.map((k, i) => `  ${i + 1}. ${k}`).join('\n')
    updatedContent += '\n\n'
  }

  // Add recommendations section
  updatedContent += 'RECOMMENDATIONS:\n'
  updatedContent += '─────────────────────────────────────────────────────────\n'

  const highPriority = recommendations.filter(r => r.priority === 'high')
  const mediumPriority = recommendations.filter(r => r.priority === 'medium')
  const lowPriority = recommendations.filter(r => r.priority === 'low')

  if (highPriority.length > 0) {
    updatedContent += '\n[HIGH PRIORITY]\n'
    highPriority.forEach((rec, idx) => {
      updatedContent += `${idx + 1}. ${rec.title}\n`
      updatedContent += `   ${rec.description}\n\n`
    })
  }

  if (mediumPriority.length > 0) {
    updatedContent += '\n[MEDIUM PRIORITY]\n'
    mediumPriority.forEach((rec, idx) => {
      updatedContent += `${idx + 1}. ${rec.title}\n`
      updatedContent += `   ${rec.description}\n\n`
    })
  }

  if (lowPriority.length > 0) {
    updatedContent += '\n[LOW PRIORITY]\n'
    lowPriority.forEach((rec, idx) => {
      updatedContent += `${idx + 1}. ${rec.title}\n`
      updatedContent += `   ${rec.description}\n\n`
    })
  }

  // Add original CV
  updatedContent += '\n───────────────────────────────────────────────────────────\n'
  updatedContent += 'ORIGINAL CV CONTENT:\n'
  updatedContent += '───────────────────────────────────────────────────────────\n\n'
  updatedContent += originalCV

  // Add footer with tips
  updatedContent += '\n\n═══════════════════════════════════════════════════════════\n'
  updatedContent += 'IMPLEMENTATION TIPS:\n'
  updatedContent += '═══════════════════════════════════════════════════════════\n'
  updatedContent += '1. Naturally integrate missing keywords into your CV\n'
  updatedContent += '2. Focus on high-priority recommendations first\n'
  updatedContent += '3. Use specific examples and metrics to support claims\n'
  updatedContent += '4. Keep formatting simple and ATS-friendly\n'
  updatedContent += '5. Avoid tables, graphics, and complex layouts\n'
  updatedContent += '6. Re-run analysis after updates to verify improvements\n\n'

  return updatedContent
}

/**
 * Generate a PDF version of the updated CV
 * Returns a blob that can be downloaded
 */
export async function generateUpdatedCVPDF(data: UpdatedCVData): Promise<Buffer> {
  const content = await generateUpdatedCV(data)

  // For now, we'll generate a simple text-based format
  // PDF generation can be added later with a library like pdfkit
  const buffer = Buffer.from(content, 'utf-8')
  return buffer
}

/**
 * Generate a formatted recommendation summary
 */
export async function generateRecommendationSummary(data: UpdatedCVData): Promise<string> {
  const {
    missingKeywords,
    recommendations,
    matchScore,
    atsScore,
    keywordMatchPercentage
  } = data

  let summary = ''

  summary += 'ATS OPTIMIZER - ANALYSIS SUMMARY\n'
  summary += '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n'

  summary += 'YOUR SCORES:\n'
  summary += `┌─ Overall Match Score: ${matchScore}%\n`
  summary += `├─ ATS Readability: ${atsScore}%\n`
  summary += `└─ Keyword Match: ${keywordMatchPercentage}%\n\n`

  summary += 'KEY FINDINGS:\n'
  summary += `• ${missingKeywords.length} important keywords missing from your CV\n`
  summary += `• ${recommendations.length} recommendations to improve\n`
  summary += `• ${recommendations.filter(r => r.priority === 'high').length} high-priority items to address\n\n`

  summary += 'NEXT STEPS:\n'
  summary += '1. Add the missing keywords naturally to your CV\n'
  summary += '2. Implement high-priority recommendations\n'
  summary += '3. Review medium-priority suggestions\n'
  summary += '4. Re-run analysis to verify improvements\n'
  summary += '5. Download the updated CV when ready\n\n'

  summary += 'MISSING KEYWORDS:\n'
  missingKeywords.slice(0, 10).forEach((keyword, idx) => {
    summary += `  ${idx + 1}. ${keyword}\n`
  })

  return summary
}
